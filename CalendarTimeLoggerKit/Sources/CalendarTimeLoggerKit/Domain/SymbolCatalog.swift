import Foundation

/// One SF Symbol offered in the template icon picker.
public struct SymbolEntry: Hashable, Sendable {
    public let name: String
    /// Search terms from the system SF Symbols catalog.
    public let keywords: [String]

    public init(name: String, keywords: [String] = []) {
        self.name = name
        self.keywords = keywords
    }
}

/// A group of symbols in the icon picker.
public struct SymbolCategory: Identifiable, Hashable, Sendable {
    public let id: String
    public let title: String
    public let symbols: [SymbolEntry]

    public init(id: String, title: String, symbols: [SymbolEntry]) {
        self.id = id
        self.title = title
        self.symbols = symbols
    }
}

/// The SF Symbols a template can use as its icon.
///
/// The catalog is generated by `scripts/generate-symbol-catalog.py`, which
/// validates every name against the SF Symbols catalog installed with macOS,
/// so only symbols that exist on the deployment target are offered.
public enum SymbolCatalog {
    public static var categories: [SymbolCategory] { generatedCategories }

    /// Every symbol name, in catalog order, without duplicates.
    public static let allNames: [String] = {
        var seen = Set<String>()
        return generatedCategories.flatMap(\.symbols).map(\.name).filter { seen.insert($0).inserted }
    }()

    private static let nameSet = Set(allNames)

    public static func contains(_ name: String) -> Bool {
        nameSet.contains(name)
    }

    /// Symbols matching a query, optionally within one category. Matches the
    /// symbol name's words (`chevron.left.forwardslash` → "forwardslash"),
    /// system keywords, and category titles. An empty query returns everything.
    public static func search(_ query: String, categoryID: String? = nil) -> [String] {
        let scope = categoryID.map { id in generatedCategories.filter { $0.id == id } } ?? generatedCategories
        let terms = query.lowercased()
            .components(separatedBy: CharacterSet.alphanumerics.inverted)
            .filter { !$0.isEmpty }
        var seen = Set<String>()
        var results: [String] = []
        for category in scope {
            for entry in category.symbols where !seen.contains(entry.name) {
                let haystack = [entry.name, category.title.lowercased()] + entry.keywords
                let matches = terms.allSatisfy { term in haystack.contains { $0.contains(term) } }
                if matches {
                    seen.insert(entry.name)
                    results.append(entry.name)
                }
            }
        }
        return results
    }
}

