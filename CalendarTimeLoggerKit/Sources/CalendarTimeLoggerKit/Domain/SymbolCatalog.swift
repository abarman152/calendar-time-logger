    /// Whether a stored value already looks like an SF Symbol name
    /// (lowercase ASCII words separated by dots).
    public static func looksLikeSymbolName(_ value: String) -> Bool {
        guard let first = value.unicodeScalars.first, CharacterSet.lowercaseLetters.contains(first) || CharacterSet.decimalDigits.contains(first) else {
            return false
        }
        let allowed = CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyz0123456789.")
        return value.unicodeScalars.allSatisfy { allowed.contains($0) } && !value.hasSuffix(".") && !value.contains("..")
    }

    /// The symbol a stored icon value should display. Never returns emoji:
    /// symbol names pass through, known emoji are mapped, anything else
    /// becomes the fallback symbol. Empty input returns an empty string.
    public static func normalizedName(_ stored: String) -> String {
        let trimmed = stored.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return "" }
        if looksLikeSymbolName(trimmed) { return trimmed }
        if let mapped = mappedEmoji(trimmed) { return mapped }
        return fallbackName
    }

    /// Like `normalizedName`, but also replaces symbol names that aren't in
    /// the catalog, so the result always renders.
    public static func displayName(_ stored: String) -> String {
        let name = normalizedName(stored)
        return SymbolCatalog.contains(name) ? name : fallbackName
    }

    /// Whether a stored icon needs migrating to a symbol name.
    public static func needsMigration(_ stored: String) -> Bool {
        let trimmed = stored.trimmingCharacters(in: .whitespacesAndNewlines)
        return !trimmed.isEmpty && !looksLikeSymbolName(trimmed)
    }

    private static func mappedEmoji(_ value: String) -> String? {
        // Compare without variation selectors (U+FE0E/U+FE0F) and skin tones,
        // and try the first character alone (1.0 stored a single character).
        func strip(_ text: String) -> String {
            String(String.UnicodeScalarView(text.unicodeScalars.filter {
                $0.value != 0xFE0F && $0.value != 0xFE0E && !(0x1F3FB...0x1F3FF).contains($0.value)
            }))
        }
        let candidates = [strip(value), value.first.map { strip(String($0)) } ?? ""]
        for candidate in candidates where !candidate.isEmpty {
            if let mapped = legacyEmojiMap[candidate] { return mapped }
        }
        return nil
    }
